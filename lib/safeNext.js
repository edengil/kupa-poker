/* ============================================================================
   נתיב־המשך בטוח להפניות אחרי התחברות (גל 2, פריט 2.1).

   פרמטר next ב־/auth/callback הועבר כמו שהוא לכתובת ההפניה — open redirect:
   ‏next=//evil.com או /\evil.com היו מוציאים את המשתמש לאתר זר מיד אחרי
   התחברות לגיטימית. מעכשיו מתקבל רק נתיב פנימי נקי; כל השאר נופל ל־"/".
   ============================================================================ */

/**
 * מחזיר את next אם הוא נתיב פנימי בטוח, אחרת "/".
 * בטוח = מתחיל ב־"/" יחיד (לא "//"), בלי backslash (דפדפנים מתרגמים אותו
 * ל־"/"), בלי תווי בקרה/רווח, ובלי קידוד של "/" או "\" מיד אחרי ההתחלה
 * (‎%2f / %5c) שעלול להפוך ל־"//" בפענוח מאוחר.
 */
export function safeNextPath(next) {
  if (typeof next !== "string" || !next) return "/";
  if (!next.startsWith("/") || next.startsWith("//")) return "/";
  if (next.includes("\\")) return "/";
  if (/[\u0000-\u0020]/.test(next)) return "/";
  if (/^\/%(?:2f|5c)/i.test(next)) return "/";
  return next;
}
