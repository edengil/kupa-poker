/* טקסטי עזרה ובקשת אישור לבעלים. */

import { BOT_MARK } from "../botMark.js";

/* תיאור שורה אחת של פריט ממתין ל־DM של הבעלים — לפי סוג הפעולה:
   קנייה בשקלים (הצורה ההיסטורית), טיפ/יציאה בג'יטונים (גל 4ב). */
function pendingLine(p) {
  if (p.op === "tip") return `• ${p.name} · טיפ ${p.amount} ג'יטונים — מעל תקרת השפיות`;
  if (p.op === "cashout") return `• ${p.name} · יציאה ${p.amount} ג'יטונים — מעל תקרת השפיות`;
  return `• ${p.name} · ${p.amount}₪`;
}

/** כותרת ה־DM לפי תמהיל הממתינים: רק פעולות־כסף חריגות (גל 4ב) מקבלות
 * כותרת משלהן; קנייה/שחקן־חדש (המקור) שומרים על הנוסח ההיסטורי. */
function pendingTitle(list) {
  const hasOps = list.some((p) => p.op === "tip" || p.op === "cashout");
  const hasBuys = list.some((p) => !p.op);
  if (hasOps && !hasBuys) return "פקודת כסף חריגה מחכה לאישור";
  if (hasOps) return "ממתינים לאישור";
  return "שחקן חדש מחכה לאישור";
}

export function ownerAskText(state) {
  const list = state.pendingApprovals || [];
  if (!list.length) return null;
  return [
    `${BOT_MARK} ${pendingTitle(list)}`,
    "",
    ...list.map(pendingLine),
    "",
    "אשר שם",
    "דחה שם · טעות · לא",
    "אפשר גם בקבוצה.",
  ].join("\n");
}

